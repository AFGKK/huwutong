<?php

/**
 * M2-01 离线激活增强配置
 *
 * 控制离线 License 文件的生成与验证行为，
 * 包括 30 天有效期窗口和 RSA 加密兼容模式。
 */
return [

    /*
    |--------------------------------------------------------------------------
    | 离线文件有效期（天）
    |--------------------------------------------------------------------------
    |
    | 从离线 License 文件生成之日起计算，超过此天数后文件失效。
    | 客户端需重新生成离线文件才能继续使用。
    | 默认 30 天（M2-01 要求）。
    |
    */
    'expiration_days' => env('OFFLINE_EXPIRATION_DAYS', 30),

    /*
    |--------------------------------------------------------------------------
    | 离线文件有效期提醒（天）
    |--------------------------------------------------------------------------
    |
    | 在离线文件到期前几天开始提醒用户重新生成。
    |
    */
    'expiration_warn_days' => env('OFFLINE_EXPIRATION_WARN_DAYS', 7),

    /*
    |--------------------------------------------------------------------------
    | 允许的最大离线有效期（天）
    |--------------------------------------------------------------------------
    |
    | 即使 License 自身有效期更长，离线文件也不能超过此天数。
    | 作为安全上限，防止配置错误。
    |
    */
    'max_expiration_days' => env('OFFLINE_MAX_EXPIRATION_DAYS', 90),

    /*
    |--------------------------------------------------------------------------
    | 生成离线文件时是否在 license 表记录离线激活时间戳
    |--------------------------------------------------------------------------
    |
    | 启用后，每次生成离线文件时会更新 licenses 表的
    | offline_activated_at 字段，用于审计和追溯。
    |
    */
    'track_activations' => env('OFFLINE_TRACK_ACTIVATIONS', true),

];
