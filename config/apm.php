<?php

/**
 * APM (Application Performance Monitoring) 配置
 *
 * 控制性能监控的行为：
 * - slow_threshold_ms: 慢请求阈值（毫秒），超过此值的请求会被标记为慢请求
 * - sample_rate: 非慢请求的采样率（1/N），1 表示全部记录，100 表示 1/100
 * - retention_days: 数据保留天数，超过此期限的请求记录会被自动清理
 * - prune_batch_size: 每次清理的最大记录数，防止长时间事务
 */
return [

    'enabled' => env('APM_ENABLED', true),

    /*
    |--------------------------------------------------------------------------
    | 慢请求阈值
    |--------------------------------------------------------------------------
    |
    | 超过此时间的请求会被标记为慢请求并记录详细原因。
    |
    */
    'slow_threshold_ms' => (int) env('APM_SLOW_THRESHOLD_MS', 1000),

    /*
    |--------------------------------------------------------------------------
    | 采样率
    |--------------------------------------------------------------------------
    |
    | 非慢请求的采样比例：1/SAMPLE_RATE。
    | 1 表示全部记录，100 表示随机 1% 的记录。
    | 慢请求不受采样率影响，全部记录。
    |
    */
    'sample_rate' => (int) env('APM_SAMPLE_RATE', 100),

    /*
    |--------------------------------------------------------------------------
    | 数据保留天数
    |--------------------------------------------------------------------------
    |
    | 超过此天数的请求记录会被定时任务自动清理。
    |
    */
    'retention_days' => (int) env('APM_RETENTION_DAYS', 7),

    /*
    |--------------------------------------------------------------------------
    | 清理批次大小
    |--------------------------------------------------------------------------
    |
    | 每次清理操作最多删除的记录数，防止长时间事务锁表。
    |
    */
    'prune_batch_size' => (int) env('APM_PRUNE_BATCH_SIZE', 1000),

    /*
    |--------------------------------------------------------------------------
    | DB 慢查询阈值（毫秒）
    |--------------------------------------------------------------------------
    |
    | 单条数据库查询超过此时间的被视为慢查询。
    | 仅在 Telescope 中用于标记慢查询，APM 中作为慢请求分析参考。
    |
    */
    'db_slow_threshold_ms' => (int) env('APM_DB_SLOW_THRESHOLD_MS', 100),
];
